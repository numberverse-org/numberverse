#!/usr/bin/env python3
"""🚀 BACKLOG 300 — oracle-driven roadmap generator (v2, data-driven).

Generates the next ~190 Numberverse backlog issues across 8 new epics so the
board holds ~300 open issues (of which ~100+ are features). Every issue gets a
Goal + Done-when acceptance criteria, milestone, and labels. Idempotent:
skips titles that already exist on the repo. Mirrors the plan into
docs/ROADMAP_NEXT.md. Milestones are created on demand.
"""
import subprocess, json, sys

REPO = "numberverse-org/numberverse"

def existing_titles():
    out = subprocess.run(["gh", "issue", "list", "--repo", REPO, "--state", "all",
                          "--limit", "600", "--json", "title"],
                         capture_output=True, text=True)
    try:
        return {t["title"] for t in json.loads(out.stdout)}
    except Exception:
        return set()

EX = existing_titles()

def B(goal, *done):
    parts = [f"## Goal\n{goal}\n", "## Done when"]
    parts += [f"- [ ] {d}" for d in done]
    return "\n".join(parts)

def ensure_milestone(title):
    try:
        r = subprocess.run(["gh", "api", f"repos/{REPO}/milestones",
                            "--jq", "[.[] | select(.title == \"" + title.replace('"', '') + "\")] | length"],
                           capture_output=True, text=True)
        if r.stdout.strip() == "0":
            subprocess.run(["gh", "api", "-X", "POST", f"repos/{REPO}/milestones",
                            "-f", f"title={title}", "-f", "description=Oracle epic 2026-08-12"],
                           capture_output=True, text=True)
    except Exception:
        pass

