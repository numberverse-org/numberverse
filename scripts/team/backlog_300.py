def create(ms, pri, labels, title, body):
    if title in EX:
        return None, "exists"
    ensure_milestone(ms)
    args = ["gh", "issue", "create", "--repo", REPO,
            "--title", title, "--body", body, "--label", f"priority: {pri}",
            "--label", "feature" if "deferred" not in labels and "guardrail" not in labels and "documentation" not in labels else ("enhancement" if "deferred" in labels else ("feature" if "guardrail" in labels else "feature")),
            "--milestone", ms]
    for l in labels:
        args += ["--label", l]
    r = subprocess.run(args, capture_output=True, text=True)
    url = r.stdout.strip().splitlines()[-1] if r.stdout.strip() else None
    if r.returncode != 0:
        return None, (r.stderr or r.stdout).strip()
    return url, "ok"

def main():
    created, skipped, errors = [], [], []
    n = len(ROADMAP)
    for i, (ms, pri, labels, t, b) in enumerate(ROADMAP, 1):
        url, status = create(ms, pri, labels, t, b)
        if url: created.append((t, url))
        elif status == "exists": skipped.append(t)
        else: errors.append((t, status))
        sys.stderr.write(f"\r{i}/{n}  created={len(created)} skipped={len(skipped)} errors={len(errors)}  ")
    sys.stderr.write("\n")
    print(f"TOTAL {n} | created {len(created)} | skipped {len(skipped)} | errors {len(errors)}")
    for t, e in errors[:10]: print(f"  ERROR {t}: {e}")

    md = ["# 🗺️ ROADMAP_NEXT — oracle-driven next-300 backlog\n",
          "> Generated 2026-08-12 from a CLEAN Oracle standup (35/35) + Council (70/70).",
          "> 8 new epics · ~190 new issues · every one scoped with acceptance criteria.\n"]
    cur = None
    for (ms, pri, labels, t, b) in ROADMAP:
        if ms != cur:
            md.append(f"\n## {ms}\n")
            cur = ms
        md.append(f"- {t}  _(priority: {pri}, {', '.join(labels)})_")
    open("docs/ROADMAP_NEXT.md", "w", encoding="utf-8").write("\n".join(md) + "\n")
    print(f"docs/ROADMAP_NEXT.md written ({len(ROADMAP)} issues)")

if __name__ == "__main__":
    main()
